export const WORLD_VIEWBOX_WIDTH = 1000;
export const WORLD_VIEWBOX_HEIGHT = 480;

const MIN_LAT = -60;
const MAX_LAT = 78;

export function lonLatToXY(lon: number, lat: number): [number, number] {
  const clampedLon = Math.max(-180, Math.min(180, lon));
  const clampedLat = Math.max(MIN_LAT, Math.min(MAX_LAT, lat));
  const x = ((clampedLon + 180) / 360) * WORLD_VIEWBOX_WIDTH;
  const y = ((MAX_LAT - clampedLat) / (MAX_LAT - MIN_LAT)) * WORLD_VIEWBOX_HEIGHT;
  return [Number(x.toFixed(1)), Number(y.toFixed(1))];
}

function polygonToPath(points: [number, number][]): string {
  if (points.length === 0) return "";
  return (
    points
      .map(([lon, lat], idx) => {
        const [x, y] = lonLatToXY(lon, lat);
        return `${idx === 0 ? "M" : "L"}${x},${y}`;
      })
      .join(" ") + " Z"
  );
}

